-- =========================================================
-- V5:自助安全——令牌版本化
-- 口径:token_version 进 JWT 的 ver 声明,认证过滤器与登录人快照比对;
--       改密/重置/停用/强制下线自增,存量令牌下一次请求即失效;
--       建列默认 0 与"令牌无 ver 声明按 0 计"同口径,加列前的存量令牌平滑过渡不踢人
-- =========================================================

ALTER TABLE sys_user
    ADD COLUMN token_version BIGINT NOT NULL DEFAULT 0
    COMMENT '令牌版本,改密/重置/停用/强制下线自增,进 JWT ver 声明' AFTER password;
